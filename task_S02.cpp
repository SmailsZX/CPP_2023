#include <iostream>
using namespace std;

int main() {
    // Создаем 4 переменные разных типов
    int f = 42;
    int g = 12;
    cout << "ДЕЛЕНИЕ (нацело и с остатком):" << endl;
    cout << f << " / " << g << " = " << f / g << endl;        
    cout << f << " % " << g << " = " << f % g << endl;  
    
    return 0;
}